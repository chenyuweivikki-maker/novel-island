"""
灵感降级模板库 — PRD 降级策略：brainstorm_plot_ideas 失败 → 从预置的"灵感套路模板库"返回建议

当灵感生成链路（LLM）不可用时，从这里随机返回一条通用但可用的创作方向，
保证作者在任何情况下都能得到"下一步怎么写"的回应。
"""
import random

TEMPLATES = [
    {
        "title": "旧物线索",
        "idea": "让主角在整理旧物时发现一件与主线相关的物品：一张旧照片、一封没寄出的信、一把打不开的钥匙。这个物品将把故事引向新的方向。",
    },
    {
        "title": "意外来客",
        "idea": "一个意想不到的人物突然登场——多年未见的老友、声称认识主角的陌生人、带着秘密前来的反派。TA 的到来打破当前平衡。",
    },
    {
        "title": "误会与真相",
        "idea": "让主角发现之前的一个判断是错的：一直被当作敌人的角色其实在暗中保护 TA，而看似可靠的人却另有图谋。",
    },
    {
        "title": "环境骤变",
        "idea": "让环境本身成为冲突：一场暴雨困住所有人、停电、城市封锁、重要场所被毁。把人物逼入不得不行动的境地。",
    },
    {
        "title": "旧伤复发",
        "idea": "触及主角最深的旧伤——曾经逃避的人和事重新出现，主角必须直面自己一直在回避的真相。",
    },
    {
        "title": "身份反转",
        "idea": "给某个配角一个身份反转：TA 隐瞒的真实身份被揭开，重新定义主角与 TA 的关系和故事走向。",
    },
    {
        "title": "承诺与代价",
        "idea": "主角许下或收到一个承诺，兑现它需要付出意想不到的代价。让读者看到角色的选择与底线。",
    },
    {
        "title": "错过与重逢",
        "idea": "主角与一个重要人物擦肩而过——在人群中、在电话里、在信纸上。这个「差一点」成为后续剧情的伏笔。",
    },
]


def fallback_inspiration(current_context: str = "") -> str:
    """返回一条模板灵感（附当前上下文提示，保证不算完全无关）"""
    t = random.choice(TEMPLATES)
    ctx = current_context.strip()
    if ctx:
        ctx_line = f"结合你当前的剧情（{ctx[:80]}），"
    else:
        ctx_line = ""
    return (
        f"（灵感服务暂时不可用，以下为预设套路方向，供你参考）\n\n"
        f"**方向：{t['title']}**\n{t['idea']}\n\n"
        f"{ctx_line}可以试试把这条和你的主线结合，或者换个方向：直接告诉我你卡在哪一段，我再帮你细想。"
    )
