def fallback_inspiration(current_context: str = "") -> str:
    """返回一条模板灵感（附当前上下文提示，保证不算完全无关）"""
    t = random.choice(TEMPLATES)
    ctx = current_context.strip()
    if ctx:
        ctx_line = f"结合你当前的剧情（{ctx[:80]}），"
    else:
        ctx_line = ""
    return (
        f"（灵感服务暂时不可用，以下为预设套路方向，供你参考）\n\n"
        f"**方向：{t['title']}**\n{t['idea']}\n\n"
        f"{ctx_line}可以试试把这条和你的主线结合，或者换个方向：直接告诉我你卡在哪一段，我再帮你细想。"
    )


def general_opening_fallback(query: str = "") -> str:
    """无项目对话兜底开场白：LLM 不可用时保证作者仍能得到自然的回应。

    （修复：该函数历史上被调用但从未定义，LLM 失败路径会二次抛错——现在补上。）
    """
    q = (query or "").strip()
    if any(k in q for k in ("题材", "类型", "都市", "奇幻", "悬疑", "古风", "科幻", "百合")):
        return "这个题材很有的写！我们先把书名定了，然后聊聊主角——ta 是什么样的人？"
    if "叫" in q and len(q) >= 6:
        return "好呀，书名和题材我记下了！点左侧「＋ 新建项目」创建这本书，我把这些信息直接入库，再陪你搭人设和大纲。"
    return ("嗨，我是你的写作搭子小说猫。还没进入任何作品，我们先从开一本新书开始："
            "书名想叫什么？什么题材（都市 / 奇幻 / 悬疑 / 古风 / 科幻…）？"
            "定了之后，我陪你把人设、配角、大纲一步步搭起来——有零散素材也可以直接拖进来，我帮你整理入库。")
